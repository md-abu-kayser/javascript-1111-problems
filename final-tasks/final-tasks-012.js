  // Requirement: Tokenize a small expression language into identifiers, numbers, strings and operators.
  class TodoApp {
    constructor() {
      this.todos = [];
    }

    createLexer(source) {
      const tokens = [];
      let position = 0;

      const patterns = [
        ["NUMBER", /^\d+(?:\.\d+)?/],
        ["IDENTIFIER", /^[A-Za-z_][A-Za-z0-9_]*/],
        ["STRING", /^"(?:[^"\\]|\\.)*"/],
        ["OPERATOR", /^[+\-*/=]/],
        ["LPAREN", /^\(/],
        ["RPAREN", /^\)/],
        ["COMMA", /^,/],
      ];

      while (position < source.length) {
        const remaining = source.slice(position);

        if (/^\s/.test(remaining)) {
          position++;
          continue;
        }

        let matched = false;

        for (const [type, regex] of patterns) {
          const match = remaining.match(regex);

          if (match) {
            tokens.push({
              type,
              value: match[0],
              position,
            });

            position += match[0].length;
            matched = true;
            break;
          }
        }

        if (!matched) {
          throw new Error(`Unexpected character at ${position}`);
        }
      }

      return tokens;
    }
  }

  // Example
  const myTodos = new TodoApp();

