  // Requirement: Parse arithmetic expressions using binding powers rather than hard-coded precedence layers.
  class TodoApp {
    constructor() {
      this.todos = [];
    }

    createPrattParser(tokens) {
      let position = 0;

      const peek = () => tokens[position];

      const consume = () => tokens[position++];

      const bindingPower = (operator) => {
        if (operator === "*" || operator === "/") {
          return 20;
        }

        if (operator === "+" || operator === "-") {
          return 10;
        }

        return 0;
      };

      const parse = (minimumBindingPower = 0) => {
        let token = consume();

        if (!token) {
          throw new Error("Unexpected end of input");
        }

        let left;

        if (token.type === "NUMBER") {
          left = {
            type: "Literal",
            value: Number(token.value),
          };
        } else if (token.type === "LPAREN") {
          left = parse(0);

          if (consume()?.type !== "RPAREN") {
            throw new Error("Expected ')'");
          }
        } else {
          throw new Error(`Unexpected token ${token.value}`);
        }

        while (peek() && bindingPower(peek().value) > minimumBindingPower) {
          const operator = consume();
          const right = parse(bindingPower(operator.value));

          left = {
            type: "BinaryExpression",
            operator: operator.value,
            left,
            right,
          };
        }

        return left;
      };

      return parse();
    }
  }

