  // Requirement: Execute stack bytecode produced by compileToBytecode using a small virtual machine.
  class TodoApp {
    constructor() {
      this.todos = [];
    }

    runBytecode(bytecode) {
      const stack = [];

      for (const instruction of bytecode) {
        switch (instruction.op) {
          case "PUSH":
            stack.push(instruction.value);
            break;

          case "ADD": {
            const right = stack.pop();
            const left = stack.pop();
            stack.push(left + right);
            break;
          }

          case "SUB": {
            const right = stack.pop();
            const left = stack.pop();
            stack.push(left - right);
            break;
          }

          case "MUL": {
            const right = stack.pop();
            const left = stack.pop();
            stack.push(left * right);
            break;
          }

          case "DIV": {
            const right = stack.pop();
            const left = stack.pop();
            stack.push(left / right);
            break;
          }

          default:
            throw new Error(`Unknown opcode: ${instruction.op}`);
        }
      }

      if (stack.length !== 1) {
        throw new Error("Invalid bytecode stack state");
      }

      return stack[0];
    }
  }

