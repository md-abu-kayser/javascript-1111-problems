  // Requirement: Compile a simple AST into stack-machine bytecode instructions.
  class TodoApp {
    constructor() {
      this.todos = [];
    }

    compileToBytecode(node) {
      const bytecode = [];

      const emit = (instruction) => {
        bytecode.push(instruction);
      };

      const compile = (current) => {
        if (current.type === "Literal") {
          emit({
            op: "PUSH",
            value: current.value,
          });

          return;
        }

        compile(current.left);
        compile(current.right);

        const opcode = {
          "+": "ADD",
          "-": "SUB",
          "*": "MUL",
          "/": "DIV",
        }[current.operator];

        if (!opcode) {
          throw new Error("Unsupported operator");
        }

        emit({
          op: opcode,
        });
      };

      compile(node);

      return bytecode;
    }
  }

